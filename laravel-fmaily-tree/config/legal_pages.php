## 1. التفسير والتعريفات

### التفسير

يكون للكلمات التي تبدأ أحرفها الأولى بحرف كبير المعاني المحددة في الشروط التالية. وينطبق التعريف نفسه سواء وردت الكلمة بصيغة المفرد أو الجمع.

### التعريفات

- **الحساب:** حساب فريد يتم إنشاؤه لك للوصول إلى الخدمة أو أجزاء منها.
- **الشركة** (ويُشار إليها بـ «نحن» أو «لنا» أو «خاصتنا»): تطبيق عائلة السّرِيع، الجهة القائمة على تشغيل الخدمة.
- **التطبيق:** تطبيق عائلة السّرِيع، وهو البرنامج المقدم من الشركة.
- **الموقع الإلكتروني:** موقع عائلة السّرِيع المتاح عبر الإنترنت.
- **الخدمة:** التطبيق والموقع الإلكتروني وأي خدمات مرتبطة بهما.
- **البلد:** المملكة العربية السعودية.
- **الجهاز:** أي جهاز يمكنه الوصول إلى الخدمة، مثل الحاسب أو الهاتف المحمول أو الجهاز اللوحي.
- **البيانات الشخصية:** أي معلومات تتعلق بشخص محدد الهوية أو قابل للتعريف، وتشمل البيانات الشخصية والبيانات الصحية وبيانات الاستخدام.
- **البيانات الصحية (Health Data):** البيانات المتعلقة بصحتك أو لياقتك البدنية أو نشاطك الحركي، مثل عدد الخطوات والمسافة والسعرات الحرارية ومدة النشاط ومصدر بيانات اللياقة، وكذلك معلومات الرضاعة والملاحظات الصحية التي تختار تقديمها.
- **بيانات الاستخدام:** بيانات تُجمع تلقائياً نتيجة استخدام الخدمة أو من البنية التحتية للخدمة، مثل مدة الزيارة والصفحات التي تمت زيارتها.
- **مزود الخدمة:** أي شخص طبيعي أو اعتباري يعالج البيانات نيابة عن الشركة، مثل شركات الاستضافة والحوسبة السحابية والرسائل والذكاء الاصطناعي.
- **أنت:** الشخص الذي يصل إلى الخدمة أو يستخدمها، أو الجهة التي يمثلها.

## 2. نطاق السياسة وموافقتك

تنطبق هذه السياسة على البيانات التي نجمعها من خلال التطبيق والموقع الإلكتروني والقنوات المرتبطة بهما. باستخدامك للخدمة أو إنشائك حساباً أو استخدامك للميزات التي تتطلب بيانات شخصية، فإنك تقر بأنك قرأت هذه السياسة ووافقت على معالجة بياناتك وفقاً لها.

إذا كنت تستخدم الخدمة نيابة عن شخص آخر، أو تضيف بيانات أفراد عائلتك، فإنك تقر بأن لديك الصلاحية أو الموافقة اللازمة لإضافة تلك البيانات ومشاركتها.

## 3. البيانات التي نجمعها

### 3.1 البيانات التي تقدمها لنا مباشرة

قد نطلب منك تقديم معلومات شخصية للتواصل معك أو التعريف بك، وتشمل على سبيل المثال لا الحصر:

- الاسم الأول واسم العائلة.
- البريد الإلكتروني ورقم الجوال ورقم واتساب عند تقديمه.
- تاريخ الميلاد ومكان الميلاد ومكان الإقامة.
- الصورة الشخصية والسيرة الذاتية والمهنة.
- بيانات التواصل التي تختار إضافتها، مثل أرقام الهاتف وحسابات التواصل الاجتماعي.
- محتوى تشاركه معنا، مثل القصص والأخبار والتعليقات والرسائل المرسلة إلى الدعم الفني.
- بيانات قد يضيفها مسؤولو العائلة أو أقاربك ضمن شجرة العائلة.

### 3.2 بيانات شجرة العائلة والعلاقات الأسرية

لتقديم خدمة توثيق الأنساب والتواصل العائلي، قد نجمع ونعالج بيانات تتعلق بالعلاقات الأسرية، مثل:

- صلة القرابة والأب والأم والزوج/الزوجة والأبناء.
- بيانات الأقارب الذين تتم إضافتهم إلى الشجرة.
- المناسبات العائلية والمجالس والبرامج والمسابقات التي تشارك فيها.
- بيانات العضوية في المجموعات والبرامج والمبادرات العائلية.

### 3.3 البيانات الصحية وبيانات اللياقة البدنية (Health Data)

قد نصل إلى البيانات الصحية أو بيانات اللياقة البدنية أو نجمعها عند استخدامك للميزات المتعلقة بالصحة والنشاط البدني، وذلك في الحدود التالية:

- **بيانات المشي والنشاط:** عدد الخطوات، والمسافة المقطوعة، ومدة النشاط، والسعرات الحرارية المحروقة، والملاحظات التي تضيفها، وتاريخ النشاط.
- **مصدر البيانات:** قد تكون البيانات مدخلة يدوياً، أو مستمدة من الجهاز، أو من خدمات مثل Apple Health أو Health Connect أو Google Fit بعد منحك الإذن.
- **بيانات الرضاعة:** صلة الأم والطفل، وتواريخ بدء الرضاعة وانتهائها، وأي ملاحظات تضيفها في هذا الشأن.
- **البيانات الصحية التي تقدمها طوعاً:** أي معلومات صحية تختار كتابتها في سيرتك الذاتية أو قصصك أو رسائل الدعم أو أي محتوى آخر.
- **بيانات اللياقة والاهتمامات:** تفاعلك مع مواقع الصحة واللياقة واستعارة الأدوات الرياضية والبرامج والمبادرات الصحية.

لا نصل إلى سجلاتك الطبية الرسمية أو نتائج التحاليل أو التشخيصات الطبية أو ملفات المستشفيات، إلا إذا قمت أنت بتقديمها إلينا طوعاً ضمن محتوى تختار مشاركته.

### 3.4 بيانات الصور والتعرّف على الوجه

قد نعالج الصور التي ترفعها إلى الخدمة، بما في ذلك صورك الشخصية وصور أفراد العائلة، لأغراض العرض داخل شجرة العائلة والمعرض والميزات المرتبطة بها. وعند استخدامك لميزة البحث بالوجه أو التحقق من الهوية بالوجه، قد نستخدم خدمات تحليل الوجه لدى مزود خدمة موثوق لإنشاء بصمة رقمية للوجه ومقارنتها بالصور المتاحة، وذلك بهدف العثور على صورك أو التحقق من هويتك داخل المنصة فقط.

لا نستخدم التعرّف على الوجه لأغراض إعلانية أو تجارية، ولا نبيع بصمات الوجه أو نشاركها مع أطراف غير مصرح لها. ويمكنك عدم استخدام هذه الميزة، أو طلب حذف بياناتك المرتبطة بها، وفقاً لما هو موضح في قسم حقوقك.

### 3.5 بيانات الاستخدام والبيانات التقنية

تُجمع بيانات الاستخدام تلقائياً عند استخدام الخدمة، وقد تشمل:

- عنوان بروتوكول الإنترنت (IP).
- نوع المتصفح وإصداره ونظام التشغيل ونوع الجهاز.
- الصفحات التي تزورها ووقت الزيارة وتاريخها والمدة المستغرقة.
- معرّفات الجهاز والبيانات التشخيصية.
- بيانات تقريبية عن الموقع الجغرافي المستمدة من عنوان IP (مثل الدولة أو المدينة)، دون تحديد موقعك الدقيق.
- سجلات الأخطاء والأداء وسجلات الأمان.

### 3.6 الموقع الجغرافي

قد نطلب إذن الوصول إلى موقعك الجغرافي عند استخدام ميزات تتطلب ذلك، مثل إضافة موقع شخص أو مكان أو فعالية. وفي حال منحك الإذن، قد نستخدم الموقع لتقديم الميزة المطلوبة فقط. يمكنك رفض الإذن أو إلغاؤه في أي وقت من إعدادات جهازك، مع العلم أن بعض الميزات قد لا تعمل دون هذا الإذن.

### 3.7 ملفات تعريف الارتباط والتقنيات المشابهة

نستخدم ملفات تعريف الارتباط الضرورية لتشغيل الخدمة والحفاظ على جلسة تسجيل الدخول وتذكر تفضيلاتك وأمان الاستخدام. ولا نستخدم حالياً ملفات تعريف ارتباط إعلانية تابعة لجهات خارجية. يمكنك ضبط إعدادات المتصفح لرفض بعض ملفات تعريف الارتباط، غير أن ذلك قد يؤثر على عمل بعض أجزاء الخدمة.

## 4. كيف نجمع البيانات

نجمع البيانات بالطرق التالية:

- **مباشرة منك:** عندما تنشئ حساباً أو تملأ نموذجاً أو ترفع صورة أو تضيف بيانات إلى شجرة العائلة أو تتواصل مع الدعم.
- **تلقائياً:** عند استخدامك الخدمة، من خلال سجلات الخادم وبيانات الاستخدام والجهاز وملفات تعريف الارتباط.
- **من خدمات اللياقة والأجهزة:** عندما تمنح التطبيق إذناً للوصول إلى بيانات النشاط أو الخطوات من Apple Health أو Health Connect أو Google Fit أو مستشعرات الجهاز.
- **من أفراد العائلة أو مسؤولي المنصة:** عندما يضيفون بياناتك إلى شجرة العائلة أو إلى مناسبة أو برنامج عائلي.
- **من مزودي الخدمة:** عندما تعالج خدمات الاستضافة أو الرسائل أو الذكاء الاصطناعي أو التعرّف على الوجه بيانات مرتبطة بتقديم الخدمة.

## 5. كيف نستخدم بياناتك

قد نستخدم بياناتك الشخصية للأغراض التالية:

- **تقديم الخدمة وصيانتها:** بما في ذلك عرض شجرة العائلة والملفات الشخصية والمعرض والأخبار والمناسبات والبرامج والمسابقات.
- **إدارة الحساب:** إدارة تسجيلك ومنحك إمكانية الوصول إلى وظائف الخدمة.
- **التواصل معك:** عبر البريد الإلكتروني أو الهاتف أو الرسائل النصية أو واتساب أو إشعارات التطبيق، بشأن تحديثات الخدمة أو التنبيهات الأمنية أو المعلومات المتعلقة بالمناسبات والبرامج العائلية.
- **تشغيل ميزات الصحة واللياقة:** حساب الخطوات والمسافة والسعرات الحرارية وعرض لوحات الترتيب والتحديات والبرامج الصحية.
- **تخصيص المحتوى:** عرض المحتوى والبرامج والمناسبات والمواقع الصحية الأكثر صلة باهتماماتك.
- **تحسين الخدمة:** تحليل استخدام الميزات وتحديد الأعطال وتطوير تجربة المستخدم.
- **الأمان ومكافحة إساءة الاستخدام:** حماية الحسابات ومنع الاحتيال والسلوك المخالف وحماية حقوق العائلة والمستخدمين.
- **الالتزامات القانونية:** الامتثال للأنظمة واللوائح والطلبات القضائية أو التنظيمية المعمول بها.
- **أغراض أخرى:** قد نستخدم معلوماتك لأغراض أخرى مثل إجراء التحليلات وإعداد الإحصاءات المجمعة، مع إخطارك وطلب موافقتك متى كان ذلك مطلوباً نظاماً.

## 6. إفصاح البيانات

نفصح في هذا القسم عن كيفية الوصول إلى بياناتك واستخدامها والإفصاح عنها، وعن الممارسات الخاصة بالبيانات الصحية على وجه التحديد.

> **إفصاح صريح بشأن البيانات الصحية (Health Data):** قد تصل الخدمة إلى البيانات الصحية أو بيانات اللياقة البدنية أو تجمعها، ولكن ذلك يقتصر على البيانات اللازمة لتقديم الميزات الصحية والرياضية التي تختار استخدامها، وبعد منحك الأذونات اللازمة. ولا نستخدم هذه البيانات للإعلانات أو للتقييم التأميني أو التوظيفي، ولا نبيعها.

### 6.1 البيانات الصحية: الوصول والجمع والاستخدام

- **الوصول:** لا نصل إلى البيانات الصحية إلا بعد منحك إذناً صريحاً عبر نظام التشغيل أو إعدادات التطبيق، أو بعد إدخالك البيانات بنفسك. ويمكنك إلغاء هذا الإذن في أي وقت من إعدادات جهازك.
- **الجمع:** نجمع فقط البيانات اللازمة للميزة التي تستخدمها، مثل الخطوات والمسافة والمدة والسعرات الحرارية ومصدر البيانات ومعلومات الجهاز، أو بيانات الرضاعة والملاحظات التي تضيفها.
- **الاستخدام:** نستخدم البيانات الصحية لتشغيل ميزات المشي واللياقة والتحديات ولوحات الترتيب، وحساب الإحصاءات، وإظهار تقدمك وتفضيلاتك، وتحسين جودة الخدمة.
- **عدم الاستخدام لأغراض أخرى:** لا نستخدم البيانات الصحية في الإعلانات أو التسويق أو بيع البيانات أو تقييم الأهلية الائتمانية أو التأمينية أو قرارات التوظيف.
- **المشاركة:** لا نشارك البيانات الصحية إلا بموافقتك الصريحة، أو مع مزودي خدمة يقدمون وظيفة تقنية ضرورية بموجب التزامات تعاقدية وسرية، أو في صورة إحصاءات مجمعة ومجهولة الهوية لا يمكن ربطها بك، أو عند وجود التزام نظامي.
- **الاحتفاظ والحذف:** نحتفظ بالبيانات الصحية للمدة اللازمة لتقديم الميزة أو طالما كان حسابك نشطاً، ثم نحذفها أو نجعلها مجهولة الهوية، ويمكنك طلب حذفها في أي وقت.

### 6.2 المشاركة مع مزودي الخدمة

قد نشارك بياناتك مع مزودي خدمة يقدمون وظائف تقنية نيابة عنا، مثل الاستضافة والتخزين السحابي، وإرسال الرسائل والإشعارات، وخدمات الذكاء الاصطناعي لمعالجة استفساراتك، وخدمات التعرّف على الوجه، وخدمات تحليل الاستخدام والبريد الإلكتروني. ونلزم هؤلاء المزودين باستخدام البيانات للغرض المحدد فقط ووفقاً لالتزامات السرية والأمان المناسبة.

### 6.3 المشاركة داخل المنصة ومع أفراد العائلة

تحتوي الخدمة على مناطق مشتركة، مثل شجرة العائلة والملفات الشخصية والمعرض والأخبار والمناسبات والمجموعات. وعندما تختار نشر بياناتك أو التفاعل في هذه المناطق، فقد تكون هذه البيانات مرئية لأفراد العائلة أو لعموم الزوار بحسب إعدادات الخصوصية الخاصة بك. ننصحك بمراجعة إعدادات الخصوصية قبل نشر أي بيانات حساسة.

### 6.4 المعاملات التجارية

إذا انخرطت الشركة في عملية اندماج أو استحواذ أو بيع لأصول، فقد تنتقل بياناتك الشخصية ضمن الأصول المنقولة. وسنقدم إشعاراً قبل نقل بياناتك وخضوعها لسياسة خصوصية مختلفة.

### 6.5 إنفاذ القانون والمتطلبات النظامية

قد نكشف عن بياناتك إذا كان ذلك مطلوباً بموجب القانون أو استجابةً لطلبات صحيحة من السلطات العامة المختصة، أو إذا اعتقدنا بحسن نية أن ذلك ضروري من أجل:

- الامتثال لالتزام قانوني أو نظامي.
- حماية حقوق الشركة أو ممتلكاتها أو الدفاع عنها.
- منع أو التحقيق في مخالفات محتملة مرتبطة بالخدمة.
- حماية سلامة مستخدمي الخدمة أو الجمهور.
- الحماية من المسؤولية القانونية.

### 6.6 ما لا نفعله ببياناتك

- لا نبيع بياناتك الشخصية أو البيانات الصحية.
- لا نستخدم البيانات الصحية لأغراض إعلانية أو تسويقية.
- لا نشارك بياناتك مع أطراف خارجية لأغراضها التجارية الخاصة دون موافقتك.
- لا نستخدم صورك أو بصمات الوجه الخاصة بك لأغراض غير مرتبطة بالخدمة.
- لا نجمع بيانات صحية من تطبيقات أو أجهزة أخرى دون إذنك.

## 7. الاحتفاظ بالبيانات

نحتفظ ببياناتك الشخصية فقط للمدة اللازمة لتحقيق الأغراض الموضحة في هذه السياسة، بما في ذلك:

- **بيانات الحساب:** مدة استمرار علاقتك بالحساب، ولمدة تصل إلى 24 شهراً بعد إغلاق الحساب لمعالجة أي أمور لاحقة أو نزاعات.
- **بيانات الاستخدام والسجلات:** لمدة تصل إلى 24 شهراً لأغراض الأمان وتحليل الأداء وتحسين الخدمة.
- **البيانات الصحية وبيانات اللياقة:** للمدة اللازمة لتقديم الميزة أو طالما كان حسابك نشطاً، ثم تُحذف أو تُجمع بصورة مجهولة الهوية.
- **محتوى العائلة:** يبقى ضمن شجرة العائلة والمعرض والأرشيف العائلي وفقاً لطبيعة الخدمة وإعدادات الخصوصية، ما لم تطلب حذفه.

قد نحتفظ ببعض البيانات لمدة أطول عند وجود التزام نظامي، أو لحماية حقوقنا أو الدفاع عن مطالبات قانونية، أو بناءً على طلبك الصريح. وعند انتهاء مدة الاحتفاظ، نحذف البيانات أو نجعلها مجهولة الهوية بصورة آمنة، وقد تبقى نسخ احتياطية مشفرة لمدة محدودة وفقاً لدورة النسخ الاحتياطي المعتمدة.

## 8. نقل البيانات خارج المملكة

قد تتم معالجة بياناتك أو تخزينها لدى مزودي خدمات يقعون خارج المملكة العربية السعودية. وفي هذه الحالة، نتخذ الخطوات المعقولة لضمان حماية بياناتك، بما في ذلك إبرام الترتيبات التعاقدية المناسبة والتحقق من وجود ضمانات أمنية وتنظيمية ملائمة، وذلك وفقاً للأنظمة المعمول بها في المملكة.

## 9. أمان البيانات

نولي أهمية بالغة لأمان بياناتك، ونستخدم وسائل حماية معقولة تشمل الاتصال المشفر، وضوابط الوصول، وتقييد الوصول إلى البيانات على من يحتاج إليها لأداء مهامه، والمراقبة الأمنية. ومع ذلك، لا يمكن ضمان أمان أي وسيلة نقل أو تخزين إلكتروني بنسبة 100%، ولمعرفة المزيد يمكنك التواصل معنا.

في حال وقوع حادثة أمنية تؤثر على بياناتك الشخصية، سنتخذ الإجراءات اللازمة ونتواصل معك ومع الجهات المختصة متى كان ذلك مطلوباً نظاماً.

## 10. حقوقك وخياراتك

وفقاً للأنظمة المعمول بها، ولا سيما نظام حماية البيانات الشخصية في المملكة العربية السعودية، قد تكون لك الحقوق التالية:

- **الحق في الوصول:** معرفة ما إذا كنا نعالج بياناتك الشخصية والحصول على نسخة منها.
- **الحق في التصحيح:** تصحيح البيانات غير الدقيقة أو تحديثها.
- **الحق في الحذف:** طلب حذف بياناتك الشخصية عندما لا توجد حاجة مشروعة للاحتفاظ بها.
- **الحق في تقييد المعالجة أو الاعتراض عليها:** في الحالات التي يسمح بها النظام.
- **الحق في نقل البيانات:** الحصول على بياناتك بصيغة منظمة ومقروءة آلياً حيث ينطبق ذلك.
- **الحق في سحب الموافقة:** سحب موافقتك على معالجة البيانات في أي وقت، دون أن يؤثر ذلك على مشروعية المعالجة السابقة.
- **الحق في تقديم شكوى:** التواصل معنا أولاً، ثم التقدم بشكوى إلى الجهة التنظيمية المختصة في المملكة العربية السعودية عند الاقتضاء.

### 10.1 التحكم في إعدادات الخصوصية

