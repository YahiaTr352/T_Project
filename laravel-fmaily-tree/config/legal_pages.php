### 10.2 أذونات الجهاز

يمكنك التحكم في أذونات الموقع والصور والإشعارات وبيانات اللياقة والصحة من إعدادات جهازك. وإذا ألغيت إذن الوصول إلى بيانات اللياقة أو الصحة، فقد تتوقف بعض الميزات المرتبطة بها عن العمل.

### 10.3 طلب حذف الحساب أو البيانات

يمكنك تحديث بياناتك أو حذف بعضها من داخل الخدمة، أو التواصل معنا لطلب الوصول إلى بياناتك أو تصحيحها أو حذفها. وقد نطلب منك ما يثبت هويتك لحماية بياناتك. وسنستجيب لطلبك في المدة التي يحددها النظام المعمول به. وقد نحتفظ ببعض المعلومات عند وجود التزام نظامي أو أساس مشروع للاحتفاظ بها.

